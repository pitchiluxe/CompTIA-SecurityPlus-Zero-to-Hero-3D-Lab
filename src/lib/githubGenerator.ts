import type { Lab, Phase, GitHubProject, GitHubProjectFile } from '../types';

/** Same slug used for a lab's own repo and for its entry in the portfolio index. */
export function repoNameFor(lab: Lab): string {
  return lab.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function generateProject(lab: Lab): GitHubProject {
  const repoName = repoNameFor(lab);

  const files: GitHubProjectFile[] = [
    {
      path: 'README.md',
      content: labReadme(lab),
    },
    {
      path: 'architecture/overview.md',
      content: labArchitecture(lab),
    },
    {
      path: 'configs/README.md',
      content: labConfigsReadme(lab),
    },
    {
      path: 'screenshots/README.md',
      content: labScreenshotsReadme(lab),
    },
    {
      path: 'evidence/README.md',
      content: labEvidenceReadme(lab),
    },
    {
      path: 'logs/README.md',
      content: labLogsReadme(lab),
    },
    {
      path: 'reports/README.md',
      content: labReportsReadme(lab),
    },
    {
      path: 'troubleshooting/README.md',
      content: labTroubleshootingReadme(lab),
    },
    {
      path: 'lessons-learned/README.md',
      content: labLessonsLearned(lab),
    },
  ];

  return {
    labId: lab.id,
    repoName,
    files,
    generatedAt: Date.now(),
  };
}

export function serializeProject(project: GitHubProject): string {
  return JSON.stringify(project, null, 2);
}

