// ---------------------------------------------------------------------------
// Phase 25 — portfolio-level index across every built phase's labs.
//
// A single lab repo (generateProject) is the unit a hiring manager opens;
// the portfolio index below is the map that gets them there — grouped by
// exam domain so a reviewer can see coverage at a glance rather than a flat,
// unsorted list of 25+ repos.
// ---------------------------------------------------------------------------

export type PortfolioDomainSummary = {
  examDomain: string;
  labCount: number;
  labs: { title: string; repoName: string; phaseTitle: string }[];
};

export type PortfolioSummary = {
  totalLabs: number;
  totalPhases: number;
  domains: PortfolioDomainSummary[];
  files: GitHubProjectFile[];
  generatedAt: number;
};

export function generatePortfolio(phases: Phase[]): PortfolioSummary {
  const domainOrder: string[] = [];
  const byDomain = new Map<string, PortfolioDomainSummary>();

  for (const phase of phases) {
    if (!byDomain.has(phase.examDomain)) {
      domainOrder.push(phase.examDomain);
      byDomain.set(phase.examDomain, { examDomain: phase.examDomain, labCount: 0, labs: [] });
    }
    const entry = byDomain.get(phase.examDomain)!;
    for (const lab of phase.labs) {
      entry.labCount += 1;
      entry.labs.push({ title: lab.title, repoName: repoNameFor(lab), phaseTitle: phase.title });
    }
  }

  const domains = domainOrder.map((d) => byDomain.get(d)!);
  const totalLabs = domains.reduce((sum, d) => sum + d.labCount, 0);

  return {
    totalLabs,
    totalPhases: phases.length,
    domains,
    files: [{ path: 'PORTFOLIO.md', content: portfolioReadme(domains, totalLabs, phases.length) }],
    generatedAt: Date.now(),
  };
}

function portfolioReadme(domains: PortfolioDomainSummary[], totalLabs: number, totalPhases: number): string {
  const domainSections = domains
    .map((d) => {
      const rows = d.labs
        .map((l) => `| ${l.title} | ${l.phaseTitle} | \`${l.repoName}\` |`)
        .join('\n');
      return `### ${d.examDomain} (${d.labCount} lab${d.labCount === 1 ? '' : 's'})\n\n| Lab | Phase | Repository |\n| --- | --- | --- |\n${rows}\n`;
    })
    .join('\n');

  return `# Security+ Zero-to-Hero Portfolio

## Summary
${totalLabs} labs completed across ${totalPhases} phases, spanning every SY0-701 domain
below. Each lab links to its own generated repository — this file is the index,
not a replacement for opening one.

## Coverage by domain
${domainSections}
## How to use this portfolio
- Feature quality over quantity — a hiring manager will open two or three repos,
  not twenty-five. Curate the strongest, most relevant ones for the role.
- Every artifact inside a linked repo is labeled \`real\`, \`simulated\`, or
  \`prepared\` — never claim simulated work as a real-system finding.
- Never include secrets, credentials, tokens, real hostnames, or personal data
  in any linked repository, screenshot, config, or log.

---
*Generated by the Security+ Zero-to-Hero 3D Lab Platform.*
`;
}
